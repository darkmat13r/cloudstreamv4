// ASM is not a dependency of build-logic: it is AGP's `gradle-api` public API (the
// AsmClassVisitorFactory instrumentation types), so it is on the compile classpath with the
// android plugin marker. It is only used to read class headers; no bytecode is touched.

/** Writes the classes.jar ABI dump. See the `cloudstream.extension-api-jar` KDoc. */
@DisableCachingByDefault(because = "Writes a committed source file; parsing the jar is fast")
abstract class DumpExtensionApiTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val jar: RegularFileProperty

    @get:Input
    abstract val packagePrefixes: ListProperty<String>

    @get:OutputFile
    abstract val apiDump: RegularFileProperty

    @TaskAction
    fun dump() {
        apiDump.get().asFile.writeText(ExtensionApiDump.render(jar.get().asFile, packagePrefixes.get()))
    }
}

/** Fails when classes.jar's ABI differs from the committed dump. See the `cloudstream.extension-api-jar` KDoc. */
@DisableCachingByDefault(because = "A verification with no outputs; parsing the jar is fast")
abstract class CheckExtensionApiTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val jar: RegularFileProperty

    @get:Input
    abstract val packagePrefixes: ListProperty<String>

    /** `@InputFiles`, not `@InputFile`: a missing dump must reach the action and its message. */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val apiDump: RegularFileProperty

    /** Shown in the failure; the full diff is also written here. */
    @get:Input
    abstract val updateCommand: Property<String>

    @get:Internal
    abstract val diffReport: RegularFileProperty

    @TaskAction
    fun check() {
        val dumpFile = apiDump.get().asFile
        if (!dumpFile.isFile) {
            throw GradleException(
                "classes.jar ABI dump $dumpFile does not exist. Generate it with `${updateCommand.get()}` and commit it."
            )
        }
        val expected = dumpFile.readText().replace("\r\n", "\n")
        val actual = ExtensionApiDump.render(jar.get().asFile, packagePrefixes.get())
        val report = diffReport.get().asFile
        if (expected == actual) {
            report.delete()
            return
        }

        val diff = ExtensionApiDiff.unifiedDiff(
            expected.lines(), actual.lines(), "a/${dumpFile.name} (committed)", "b/${dumpFile.name} (classes.jar)"
        )
        report.parentFile.mkdirs()
        report.writeText(diff.joinToString("\n", postfix = "\n"))

        val shown = 400
        val body = if (diff.size <= shown) diff else diff.take(shown) + "... ${diff.size - shown} more diff lines"
        throw GradleException(
            buildString {
                appendLine("classes.jar ABI changed: it no longer matches $dumpFile.")
                appendLine("Third-party extensions compile against this jar and link against the running app, so every")
                appendLine("removed or changed line below can break an extension that is already published.")
                appendLine(ExtensionApiDump.summary(expected, actual))
                appendLine()
                body.forEach { appendLine(it) }
                appendLine()
                appendLine("Full diff: $report")
                appendLine("If the change is intended, run `${updateCommand.get()}`, review the api/ diff and commit it.")
            }
        )
    }
}

object ExtensionApiDump {
    private const val HEADER =
        "// ABI of app/build/classes.jar, the jar third-party extensions compile against.\n" +
            "// Generated by ./gradlew :app:dumpExtensionApi - do not edit. Checked by :app:checkExtensionApi.\n"

    /** Renders the dump: public/protected classes under [packagePrefixes], sorted, members sorted. */
    fun render(jar: File, packagePrefixes: List<String>): String {
        val blocks = ZipFile(jar).use { zip ->
            zip.entries().asSequence()
                .filter { !it.isDirectory && it.name.endsWith(".class") }
                .filter { entry -> packagePrefixes.any { entry.name.startsWith(it) } }
                .mapNotNull { entry -> zip.getInputStream(entry).use { renderClass(ClassReader(it)) } }
                .toList()
        }
        return blocks.sortedBy { it.first }.joinToString("", prefix = HEADER) { "\n" + it.second }
    }

    private fun visibility(access: Int): String? = when {
        access and Opcodes.ACC_PUBLIC != 0 -> "public"
        access and Opcodes.ACC_PROTECTED != 0 -> "protected"
        else -> null
    }

    private fun flag(access: Int, mask: Int, word: String) = if (access and mask != 0) " $word" else ""

    /** Name to rendered block, or null when the class is not public or protected. */
    private fun renderClass(reader: ClassReader): Pair<String, String>? {
        var header = ""
        var name = ""
        var classAccess = 0
        val fields = sortedMapOf<String, String>()
        val methods = sortedMapOf<String, String>()

        reader.accept(object : ClassVisitor(Opcodes.ASM9) {
            override fun visit(
                version: Int, access: Int, className: String, signature: String?, superName: String?,
                interfaces: Array<out String>?,
            ) {
                name = className
                classAccess = access
                val supertypes = listOfNotNull(superName) + interfaces.orEmpty().sorted()
                header = className + if (supertypes.isEmpty()) "" else " : " + supertypes.joinToString(", ")
            }

            // A nested class's own InnerClasses entry holds its source visibility (protected, private),
            // which the class file's access flags cannot express.
            override fun visitInnerClass(innerName: String, outerName: String?, simpleName: String?, access: Int) {
                // Inner-class flags are a superset of the class file's, so they replace them.
                if (innerName == name) classAccess = access
            }

            override fun visitField(access: Int, fieldName: String, descriptor: String, signature: String?, value: Any?): FieldVisitor? {
                // value (a constant's initial value) is deliberately ignored: BuildConfig and R change it every build.
                val visibility = visibility(access) ?: return null
                fields["$fieldName $descriptor"] = "\t$visibility" + flag(access, Opcodes.ACC_STATIC, "static") +
                    flag(access, Opcodes.ACC_FINAL, "final") + flag(access, Opcodes.ACC_SYNTHETIC, "synthetic") +
                    " field $fieldName $descriptor"
                return null
            }

            override fun visitMethod(
                access: Int, methodName: String, descriptor: String, signature: String?, exceptions: Array<out String>?,
            ): MethodVisitor? {
                val visibility = visibility(access) ?: return null
                methods["$methodName $descriptor"] = "\t$visibility" + flag(access, Opcodes.ACC_STATIC, "static") +
                    flag(access, Opcodes.ACC_ABSTRACT, "abstract") + flag(access, Opcodes.ACC_FINAL, "final") +
                    flag(access, Opcodes.ACC_SYNTHETIC, "synthetic") + " fun $methodName $descriptor"
                return null
            }
        }, ClassReader.SKIP_CODE or ClassReader.SKIP_DEBUG or ClassReader.SKIP_FRAMES)

        val visibility = visibility(classAccess) ?: return null
        val kind = when {
            classAccess and Opcodes.ACC_ANNOTATION != 0 -> "annotation"
            classAccess and Opcodes.ACC_INTERFACE != 0 -> "interface"
            classAccess and Opcodes.ACC_ENUM != 0 -> "enum"
            else -> "class"
        }
        val modality = when {
            classAccess and Opcodes.ACC_INTERFACE != 0 -> ""
            classAccess and Opcodes.ACC_ABSTRACT != 0 -> " abstract"
            classAccess and Opcodes.ACC_FINAL != 0 -> " final"
            else -> " open"
        }
        val block = buildString {
            append(visibility).append(modality).append(flag(classAccess, Opcodes.ACC_STATIC, "static"))
                .append(flag(classAccess, Opcodes.ACC_SYNTHETIC, "synthetic"))
                .append(' ').append(kind).append(' ').append(header).append(" {\n")
            fields.values.forEach { append(it).append('\n') }
            methods.values.forEach { append(it).append('\n') }
            append("}\n")
        }
        return name to block
    }

    /** Class name of a rendered block's first line, or "" for the file header. */
    private fun blockKey(firstLine: String): String =
        if (firstLine.startsWith("//")) "" else firstLine.removeSuffix(" {").substringBefore(" : ").substringAfterLast(' ')

    /** Splits lines into blank-line-terminated blocks, each keyed by its class name. */
    internal fun blocks(lines: List<String>): List<Pair<String, List<String>>> {
        val result = mutableListOf<Pair<String, List<String>>>()
        var current = mutableListOf<String>()
        lines.forEach { line ->
            current += line
            if (line.isEmpty()) {
                result += blockKey(current.first()) to current
                current = mutableListOf()
            }
        }
        if (current.isNotEmpty()) result += blockKey(current.first()) to current
        return result
    }

    fun summary(expected: String, actual: String): String {
        val before = blocks(expected.lines()).associate { it.first to it.second }
        val after = blocks(actual.lines()).associate { it.first to it.second }
        val added = (after.keys - before.keys).filter { it.isNotEmpty() }
        val removed = (before.keys - after.keys).filter { it.isNotEmpty() }
        val changed = (before.keys intersect after.keys).filter { it.isNotEmpty() && before[it] != after[it] }
        return "Classes: ${removed.size} removed, ${changed.size} changed, ${added.size} added."
    }
}
