package strings

/**
 * Writes Android `values…/strings.xml` from already-decoded values: the exact inverse of the decode path
 * [CmpStringsXml] encodes for. Where [CmpStringsXml] targets Compose's `XmlValuesConverterTask`, this targets
 * `aapt2 compile --legacy` — the same aapt2 whose decoded value is this pipeline's oracle — so a value written
 * here and compiled again decodes to the character sequence it came from.
 *
 * Every value is written **quoted**. aapt2 has two text modes (`frameworks/base/tools/aapt2/text/Utf8Iterator`,
 * `ResourceUtils::ParseStyledString`): outside quotes it trims and collapses whitespace, treats a leading `@` or
 * `?` as a reference, and rejects a bare apostrophe; inside `"…"` it does none of that. Quoting unconditionally
 * removes all four hazards at once, so the escaping below is five rules with no lookahead and no special cases:
 *
 * - `&`, `<`, `>` are XML entities — the XML parser runs before aapt2 sees the text.
 * - A backslash is doubled and a double quote is `\"`; both are aapt2 escapes that survive inside quotes.
 * - LF is `\n` and TAB is `\t`, so no significant whitespace is ever left to the XML parser's mercy.
 * - Any other C0 control, and U+FFFE/U+FFFF, are `\uXXXX`: they are not well-formed XML text (CR is also
 *   re-serialised by AGP's merger, which is why [FindingKind.CR_CHARACTER_REFERENCE] exists).
 * - Everything else — apostrophes, NBSP, RLM, `%`, astral characters — is written raw. A quoted apostrophe needs
 *   no escape, and a quoted `@string/x` is literal text rather than a reference.
 */
internal object AndroidStringsXml {
    private val PLURAL_ORDER = listOf("zero", "one", "two", "few", "many", "other")

    /** Encodes [text] for aapt2, including the surrounding quotes. */
    fun encode(text: String): String = buildString {
        append('"')
        text.forEach { c ->
            when {
                c == '&' -> append("&amp;")
                c == '<' -> append("&lt;")
                c == '>' -> append("&gt;")
                c == '\\' -> append("\\\\")
                c == '"' -> append("\\\"")
                c == '\n' -> append("\\n")
                c == '\t' -> append("\\t")
                c.code < 0x20 || c == '￾' || c == '￿' -> append("\\u%04X".format(c.code))
                else -> append(c)
            }
        }
        append('"')
    }

    /**
     * One `strings.xml` for a directory: one element per line, no whitespace inside any element.
     *
     * `formatted="true"` is re-emitted on every `<string>` holding a `%`, which is where the authored res carries
     * it (2304 occurrences, all `true`, all on `<string>`). It is aapt2's default, so it documents rather than
     * changes the value.
     */
    fun write(entries: Map<ResourceKey, TextValue>): String = buildString {
        append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
        append("<!-- Generated by :core:strings from the Compose resources. Do not edit. -->\n")
        append("<resources>\n")
        entries.toSortedMap().forEach { (key, value) ->
            when (value) {
                is TextValue.Single -> {
                    val formatted = if ('%' in value.text) " formatted=\"true\"" else ""
                    append("<string name=\"${key.name}\"$formatted>")
                    append(encode(value.text)).append("</string>\n")
                }
                is TextValue.Plural -> {
                    append("<plurals name=\"${key.name}\">")
                    value.items.entries.sortedBy { PLURAL_ORDER.indexOf(it.key) }.forEach { (category, text) ->
                        append("<item quantity=\"$category\">").append(encode(text)).append("</item>")
                    }
                    append("</plurals>\n")
                }
            }
        }
        append("</resources>\n")
    }
}
