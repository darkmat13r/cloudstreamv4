package strings

import java.io.ByteArrayOutputStream
import java.io.File
import java.util.zip.ZipFile
import org.gradle.process.ExecOperations

/**
 * The TSV files the generator writes next to the resources, for the jvmTest and for humans. Every cell is escaped
 * with [Tsv.escape]; no file contains an absolute path, so the outputs relocate across checkouts and CI runners.
 */
internal object StringsOracles {
    private const val HEADER = "# Generated by generateComposeStrings. Cells escape \\\\ \\n \\t \\r.\n"

    fun decoded(rows: List<Pair<String, DecodedEntry>>): String = HEADER + buildString {
        rows.forEach { (location, entry) ->
            val items = when (val value = entry.value) {
                is DecodedValue.Single -> listOf("-" to value.item)
                is DecodedValue.Plural -> value.items
                is DecodedValue.Other -> listOf("-" to DecodedItem.Unsupported(value.what))
            }
            items.forEach { (sub, item) ->
                val (kind, text, spans) = when (item) {
                    is DecodedItem.Text -> Triple("STR", item.text, "")
                    is DecodedItem.Styled -> Triple("STYLED", item.text, item.spans)
                    is DecodedItem.Ref -> Triple(if (item.isAttribute) "ATTR" else "REF", item.name, "")
                    is DecodedItem.Unsupported -> Triple("UNSUPPORTED", item.what, "")
                }
                row(location, entry.type, entry.name, sub, kind, text, spans)
            }
        }
    }

    fun emitted(emitted: Map<String, Map<ResourceKey, TextValue>>): String = HEADER + buildString {
        emitted.toSortedMap().forEach { (directory, entries) -> values(directory, entries) }
    }

    fun lookup(lookup: Map<String, Map<ResourceKey, TextValue>>): String = HEADER + buildString {
        lookup.forEach { (request, entries) -> values(request, entries) }
    }

    fun requests(requests: List<ParityRequest>): String = HEADER + buildString {
        requests.forEach {
            val compose = it.compose
            row(it.id, it.androidTag, compose.language, compose.script, compose.region, it.expectation, it.note)
        }
    }

    /**
     * `core/strings/parity-requests.txt`: whitespace-separated `id androidTag language script region expectation`,
     * then a free-text note; `-` is an empty script or region, `#` starts a comment line.
     */
    fun parseRequests(text: String): List<ParityRequest> = text.lines()
        .filter { it.isNotBlank() && !it.trimStart().startsWith("#") }
        .map { line ->
            val cells = line.trim().split(Regex("\\s+"), limit = 7)
            require(cells.size >= 6) { "parity request needs 6 columns: $line" }
            fun cell(i: Int) = cells[i].takeIf { it != "-" } ?: ""
            val environment = ComposeEnvironment(cell(2), cell(3), cell(4))
            ParityRequest(cells[0], cells[1], environment, cells[5], cells.getOrElse(6) { "" })
        }

    fun parseAllowlist(text: String): List<String> =
        text.lines().map { it.substringBefore('#').trim() }.filter { it.isNotEmpty() }

    private fun StringBuilder.values(first: String, entries: Map<ResourceKey, TextValue>) {
        entries.toSortedMap().forEach { (key, value) ->
            when (value) {
                is TextValue.Single -> row(first, key.type, key.name, "-", value.text)
                is TextValue.Plural -> value.items.toSortedMap().forEach { (category, text) ->
                    row(first, key.type, key.name, category, text)
                }
            }
        }
    }

    private fun StringBuilder.row(vararg cells: String) {
        cells.joinTo(this, "\t") { Tsv.escape(it) }
        append('\n')
    }
}

/**
 * Runs `aapt2 compile --legacy --dir` on the sanitised files and reads the `.flat` tables back.
 *
 * `--legacy` matches AGP, which compiles values in-process with `legacyMode = true` (`ResourceCompilerRunnable.kt:27`):
 * a translator's non-positional `%s %s` is a warning there, and must not break this module while `:app` builds.
 * There is no `link` step: the compiled table already holds every decoded value, and linking needs `android.jar`
 * and the ids of every referenced library resource.
 *
 * A failing compile fails the build in every guard mode, with aapt2's own messages (paths relative to `res/`), because
 * the same file breaks `:app`'s resource compilation too.
 */
internal class Aapt2Compiler(
    private val exec: ExecOperations,
    private val executable: File,
    private val workDir: File,
    private val findings: Findings,
) : ResourceCompiler {
    override fun compile(files: Map<String, String>): Map<String, List<DecodedEntry>> {
        workDir.deleteRecursively()
        val res = File(workDir, "res")
        files.forEach { (location, text) ->
            File(res, location).apply { parentFile.mkdirs() }.writeText(text, Charsets.UTF_8)
        }
        val compiled = File(workDir, "compiled.zip")
        val output = ByteArrayOutputStream()
        val aapt2 = executable.absolutePath
        val result = exec.exec {
            commandLine(aapt2, "compile", "--legacy", "--dir", res.absolutePath, "-o", compiled.absolutePath)
            standardOutput = output
            errorOutput = output
            isIgnoreExitValue = true
        }
        val messages = output.toString(Charsets.UTF_8).lines().filter { it.isNotBlank() }
            .map { it.replace(res.absolutePath + File.separator, "").replace(workDir.absolutePath, "<work>") }
        if (result.exitValue != 0) {
            findings.add(
                FindingKind.AAPT2_FAILED, "", "",
                "aapt2 exited with ${result.exitValue}:\n" + messages.joinToString("\n") { "    $it" },
            )
        }
        messages.forEach { findings.add(FindingKind.AAPT2_WARNING, it.substringBefore(':'), "", it) }
        return ZipFile(compiled).use { zip ->
            zip.entries().asSequence().filter { it.name.endsWith(".arsc.flat") }.associate { entry ->
                val name = entry.name.substringAfterLast('/').removeSuffix(".arsc.flat")
                val location = name.substringBefore('_') + "/" + name.substringAfter('_') + ".xml"
                location to AaptContainerReader.read(zip.getInputStream(entry).readBytes())
            }
        }
    }
}
