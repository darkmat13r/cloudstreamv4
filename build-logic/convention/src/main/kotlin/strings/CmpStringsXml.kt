package strings

import javax.xml.stream.XMLInputFactory

/** A value as Compose must return it: one text, or plural texts by category (`zero` … `other`). */
internal sealed interface TextValue {
    data class Single(val text: String) : TextValue

    data class Plural(val items: Map<String, String>) : TextValue
}

internal object CmpStringsXml {
    private val PLURAL_ORDER = listOf("zero", "one", "two", "few", "many", "other")

    /**
     * Encodes [text] so Compose Multiplatform 1.12.0's `XmlValuesConverterTask` reads it back exactly: it takes the
     * DOM `textContent`, then `handleSpecialCharacters` decodes `\n`, `\t` and `\uXXXX` and finally turns every `\\`
     * into `\` (`PrepareComposeResources.kt:295-308`).
     *
     * - A backslash is always written doubled; a single raw backslash would be eaten by that last pass.
     * - LF and TAB are written as `\n` and `\t` so no whitespace appears in the XML text at all.
     * - `&`, `<`, `>` are entities; CR, other C0 controls, U+FFFE and U+FFFF (not allowed or not preserved in XML)
     *   are written as `\uXXXX`.
     * - Everything else, including quotes, NBSP, RLM and astral characters, is written raw. Android escaping
     *   (`\'`, surrounding quotes) never appears: the input is aapt2's already-decoded value.
     */
    fun encode(text: String): String = buildString {
        text.forEach { c ->
            when {
                c == '\\' -> append("\\\\")
                c == '\n' -> append("\\n")
                c == '\t' -> append("\\t")
                c == '&' -> append("&amp;")
                c == '<' -> append("&lt;")
                c == '>' -> append("&gt;")
                c.code < 0x20 || c == '￾' || c == '￿' -> append("\\u%04X".format(c.code))
                else -> append(c)
            }
        }
    }

    /** One `strings.xml` for a directory: one element per line, no whitespace inside any element. */
    fun write(entries: Map<ResourceKey, TextValue>): String = buildString {
        append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
        append("<!-- Generated by :core:strings generateComposeStrings from app/src/main/res. Do not edit. -->\n")
        append("<resources>\n")
        entries.toSortedMap().forEach { (key, value) ->
            when (value) {
                is TextValue.Single ->
                    append("<string name=\"${key.name}\">").append(encode(value.text)).append("</string>\n")
                is TextValue.Plural -> {
                    append("<plurals name=\"${key.name}\">")
                    value.items.entries.sortedBy { PLURAL_ORDER.indexOf(it.key) }.forEach { (category, text) ->
                        append("<item quantity=\"$category\">").append(encode(text)).append("</item>")
                    }
                    append("</plurals>\n")
                }
            }
        }
        append("</resources>\n")
    }
}

/** A resource identity: `string/x` and `plurals/x` are different resources on Android and in Compose. */
data class ResourceKey(val type: String, val name: String) : Comparable<ResourceKey> {
    override fun compareTo(other: ResourceKey): Int = compareValuesBy(this, other, { it.type }, { it.name })

    override fun toString(): String = "$type/$name"
}

/**
 * Reads back what [CmpStringsXml.write] produced: the authored Compose tree, as the values it holds.
 *
 * This is the **exact inverse of [CmpStringsXml.encode]**, not a reimplementation of Compose Multiplatform's own
 * reader. `encode` emits exactly four backslash escapes (`\\`, `\n`, `\t`, `\uXXXX`) and three XML entities, so one
 * left-to-right pass decodes it unambiguously. CMP's `handleSpecialCharacters` decodes in a different order
 * (`\n`/`\t`/`\uXXXX` first, then `\\` -> `\`), which disagrees on inputs this encoder never emits; that CMP reads
 * these files correctly is a separate fact, and it is what `GeneratedResourcesParityTest` measures through the real
 * runtime.
 *
 * `verifyStringsRoundTrip` asserts that reading the committed tree reproduces the pipeline's own emitted map, value
 * for value, so this reader cannot drift from the writer without a build failing.
 *
 * DTD and external entities are off, matching [ValuesSanitizer]: these files are generated, but a reader that
 * resolves entities is a liability wherever it is pointed next.
 */
internal object CmpStringsReader {
    fun read(text: String): Map<ResourceKey, TextValue> {
        rejectDoctype(text)
        val reader = factory().createXMLStreamReader(java.io.StringReader(text))
        val entries = sortedMapOf<ResourceKey, TextValue>()
        var name: String? = null
        var type: String? = null
        var quantity: String? = null
        val chars = StringBuilder()
        val plural = LinkedHashMap<String, String>()
        while (reader.hasNext()) {
            when (reader.next()) {
                javax.xml.stream.XMLStreamConstants.START_ELEMENT -> when (reader.localName) {
                    "string", "plurals" -> {
                        type = reader.localName
                        name = reader.getAttributeValue(null, "name")
                            ?: throw StringsBuildException("a <${reader.localName}> has no name attribute")
                        chars.setLength(0)
                        plural.clear()
                    }
                    "item" -> {
                        quantity = reader.getAttributeValue(null, "quantity")
                            ?: throw StringsBuildException("a plural <item> of '$name' has no quantity")
                        chars.setLength(0)
                    }
                }
                javax.xml.stream.XMLStreamConstants.CHARACTERS,
                javax.xml.stream.XMLStreamConstants.CDATA,
                -> chars.append(reader.text)
                javax.xml.stream.XMLStreamConstants.END_ELEMENT -> when (reader.localName) {
                    "string" -> entries[ResourceKey("string", name!!)] = TextValue.Single(unescape(chars.toString()))
                    "item" -> plural[quantity!!] = unescape(chars.toString())
                    "plurals" -> entries[ResourceKey("plurals", name!!)] = TextValue.Plural(LinkedHashMap(plural))
                }
            }
        }
        reader.close()
        check(type == null || entries.isNotEmpty()) { "no entries read" }
        return entries
    }

    /** The inverse of [CmpStringsXml.encode]: one pass, and any other escape is the writer having changed. */
    private fun unescape(text: String): String = buildString {
        var i = 0
        while (i < text.length) {
            val c = text[i]
            if (c != '\\') {
                append(c)
                i++
                continue
            }
            if (i + 1 >= text.length) throw StringsBuildException("value ends in a dangling backslash: $text")
            when (val e = text[i + 1]) {
                '\\' -> { append('\\'); i += 2 }
                'n' -> { append('\n'); i += 2 }
                't' -> { append('\t'); i += 2 }
                'u' -> {
                    if (i + 6 > text.length) throw StringsBuildException("truncated \\u escape in: $text")
                    append(text.substring(i + 2, i + 6).toInt(16).toChar())
                    i += 6
                }
                else -> throw StringsBuildException("CmpStringsXml.encode never emits the escape '\\$e': $text")
            }
        }
    }

    /**
     * Refuses a DOCTYPE before any parser sees the document.
     *
     * [factory] already turns DTD support off, so StAX would throw too — but with a message about an unexpected
     * token, which reads as a typo rather than as the thing it is. More to the point, Compose Multiplatform's own
     * `XmlValuesConverterTask` parses these files with a `DocumentBuilderFactory` it does **not** harden
     * (`PrepareComposeResources.kt`), and the authored tree is now a checked-in source anyone can edit. A document
     * that never reaches a parser with entity resolution enabled is the only guarantee worth having, so this check
     * runs first and names the file's problem plainly.
     *
     * [ValuesSanitizer] does the same for `app/src/main/res` ([FindingKind.DOCTYPE], covered by the
     * `doctype-external-entity` guard case); this is that rule on the Compose side of the flip.
     */
    private fun rejectDoctype(text: String) {
        val prolog = text.take(DOCTYPE_SCAN)
        if (DOCTYPE.containsMatchIn(prolog)) {
            throw StringsBuildException(
                "DOCTYPE in a Compose values file. External entities are never resolved here, and Compose " +
                    "Multiplatform's own reader would not refuse one: remove it.",
            )
        }
    }

    private val DOCTYPE = Regex("""<!DOCTYPE""", RegexOption.IGNORE_CASE)

    /** A DOCTYPE is only legal in the prolog, so there is no reason to scan a 60 kB file to the end. */
    private const val DOCTYPE_SCAN = 4096

    private fun factory(): XMLInputFactory = XMLInputFactory.newDefaultFactory().apply {
        setProperty(XMLInputFactory.SUPPORT_DTD, false)
        setProperty(XMLInputFactory.IS_SUPPORTING_EXTERNAL_ENTITIES, false)
        setProperty(XMLInputFactory.IS_NAMESPACE_AWARE, true)
    }
}
